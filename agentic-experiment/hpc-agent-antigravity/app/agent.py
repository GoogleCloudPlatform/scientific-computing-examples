import datetime
from zoneinfo import ZoneInfo

from google.adk.agents import Agent
from google.adk.apps import App
from google.adk.models import Gemini
from google.genai import types

import os
import google.auth
from app.tools import (
    check_vm_availability,
    deploy_cluster,
    destroy_cluster,
    get_cluster_status,
    submit_slurm_job,
    get_job_status
)
from app.sub_agents import (
    vm_availability_agent,
    compute_quota_agent,
    storage_quota_agent,
    nextflow_optimizer_agent,
    cluster_blueprint_agent
)

_, project_id = google.auth.default()
os.environ["GOOGLE_CLOUD_PROJECT"] = project_id
os.environ["GOOGLE_CLOUD_LOCATION"] = "global"
os.environ["GOOGLE_GENAI_USE_VERTEXAI"] = "True"

root_agent = Agent(
    name="hpc_orchestrator_agent",
    model=Gemini(
        model="gemini-flash-latest",
        retry_options=types.HttpRetryOptions(attempts=3),
    ),
    instruction="""You are an HPC orchestrator agent capable of managing high-performance computing and batch workloads on Google Cloud. 
You have access to Google Cloud HPC Toolkit and Slurm integration tools, as well as specialized sub-agents.

DELEGATION:
When asked complex questions or tasks regarding Quotas, VM Availability, Nextflow Batch Optimization, or Cluster Toolkit Blueprints, DELEGATE to the respective sub-agent:
- vm_availability_checker
- compute_quota_checker
- storage_quota_checker
- nextflow_optimizer_agent
- cluster_blueprint_creator

EXECUTION:
Before deploying infrastructure, always check VM availability.
When asked to deploy a cluster, locate the appropriate blueprint (often generated by the cluster_blueprint_creator) and use the deploy_cluster tool.
Once deployed, you can submit and monitor Slurm jobs via SSH to the login node.
When workflows are complete and the cluster is no longer needed, tear it down using destroy_cluster to save costs.""",
    tools=[
        check_vm_availability,
        deploy_cluster,
        destroy_cluster,
        get_cluster_status,
        submit_slurm_job,
        get_job_status,
        vm_availability_agent,
        compute_quota_agent,
        storage_quota_agent,
        nextflow_optimizer_agent,
        cluster_blueprint_agent
    ],
)

app = App(
    root_agent=root_agent,
    name="app",
)
